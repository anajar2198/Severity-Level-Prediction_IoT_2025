"""Refresh runtime values in the current revised manuscript, preserving its layout.
Requires data/runtime_selective_20261105 generated by benchmark_selective_runtime.py.
Does not rebuild the paper from the historical manuscript or change BA/F1 results.
"""
from pathlib import Path
import json,re,shutil
import pandas as pd

P=Path(__file__).resolve().parents[2]
D=P/'revision_materials/data'
R=D/'runtime_selective_20261105'
assert json.loads((R/'validation.json').read_text())['passed']
assert json.loads((R/'complete.json').read_text())['state']=='complete'
runtime=pd.read_csv(R/'summary.csv')
timing=pd.read_csv(R/'runtime_table.csv').set_index(['stream','variant'])
s=(P/'main_revised.tex').read_text()

def block(label):
    i=s.index('\\label{'+label+'}')
    a=s.rfind('\\begin{table}',0,i)
    b=s.index('\\end{table}',i)+len('\\end{table}')
    return a,b,s[a:b]

def ms(stream,variant,key='total_ms'):
    return float(timing.loc[(stream,variant),key])

def full_stage(stream,stage,stat='median_ms'):
    return runtime.query('stream==@stream and feature_set=="full" and device=="cuda" and stage==@stage')[stat].item()

# Table X: retain all original labels, feature counts, BA and F1 cells verbatim.
a,b,t=block('tab:feature_pruning_anomaly2_runtime')
variants={'Full':'full',r'75\%':'top75',r'50\%':'top50',r'25\%':'top25','15/ch.':'per_channel15','10/ch.':'per_channel10'}
lines=[];stream=None
for line in t.splitlines():
    if r'\textit{PCC stream}' in line:stream='pcc'
    if r'\textit{MOTOR stream}' in line:stream='motor'
    if ' & ' in line and line.split(' & ')[0] in variants:
        cells=line.split(' & ');variant=variants[cells[0]]
        value=timing.loc[(stream,variant)]
        minimum=min(ms(stream,v) for v in variants.values())
        total=f'{value.total_ms:.2f}'
        if value.total_ms==minimum:total=r'\textbf{'+total+'}'
        line=' & '.join(cells[:4]+[f'{value.extraction_ms:.2f}',total,f'{value.speedup:.2f} '+r'\\'])
    if line.startswith(r'\par\smallskip\begin{minipage}'):
        line=r'\par\smallskip\begin{minipage}{\columnwidth}\scriptsize Performance: mean $\pm$ sample SD. Timing: seed-1234 GPU-assisted median; 95th percentiles are supplied in the results. Bold: highest BA/F1 or lowest total latency within a stream. Only selected statistics and their required intermediate calculations are evaluated.\end{minipage}'
    lines.append(line)
s=s[:a]+'\n'.join(lines)+s[b:]

# Table IX: same new full-feature baseline and timing session as Table X.
a,b,t=block('tab:runtime_latency');lines=[];stream=None
for line in t.splitlines():
    if r'\textit{PCC stream}' in line:stream='pcc'
    if r'\textit{MOTOR stream}' in line:stream='motor'
    if line.startswith('Median &') or line.startswith('95th pct. &'):
        stat='median_ms' if line.startswith('Median') else 'p95_ms'
        values=[full_stage(stream,stage,stat) for stage in ['feature_extraction','normalization_transfer_inference','end_to_end_processing']]
        rate=f'{1000/values[2]:.2f}' if stat=='median_ms' else '--'
        line=' & '.join([line.split(' & ')[0]]+[f'{v:.2f}' for v in values]+[rate])+r' \\'
    lines.append(line)
s=s[:a]+'\n'.join(lines)+s[b:]

# Replace only the timing/pruning interpretation paragraphs, retaining structure.
start=s.index('Table~\\ref{tab:feature_pruning_anomaly2_runtime}')
end=s.index('\n\n',start)
pf,pp=ms('pcc','full'),ms('pcc','top25')
mf,mp=ms('motor','full'),ms('motor','top25')
paragraph=(r'Table~\ref{tab:feature_pruning_anomaly2_runtime} quantifies the reduction in processing time obtained by selective feature computation. '
    +rf'The PCC top-25\% subset retains 18 of 74 features and approximately preserves balanced accuracy (80.29\%), while reducing processing time from {pf:.2f} to {pp:.2f}~ms ({pf/pp:.2f}$\times$). '
    +rf'The motor top-25\% subset retains 56 of 222 features and reduces processing time from {mf:.2f} to {mp:.2f}~ms ({mf/mp:.2f}$\times$), with balanced accuracy of 86.83\% compared with 88.26\% for the full input. '
    +r'For each subset, the extractor evaluates only the selected statistics and the intermediate calculations required to obtain them. Shared operations, such as the FFT, are retained when needed by a selected feature; unrelated harmonic, spectral, envelope, and time-domain calculations are omitted. The selected feature values and model outputs were verified against the original implementation, so the trained models and classification results are unchanged. Full and reduced subsets were timed using the same implementation and benchmark conditions. Speedup depends on the computational dependencies of the retained features as well as their number. All evaluated subsets are reported, and the full-feature model remains the reference.')
s=s[:start]+paragraph+s[end:]
start=s.index('Full-feature GPU-assisted processing takes')
end=s.index('\n\n',start)
p95,m95=full_stage('pcc','end_to_end_processing','p95_ms'),full_stage('motor','end_to_end_processing','p95_ms')
s=s[:start]+(f'Full-feature GPU-assisted processing takes {pf:.2f}~ms for PCC and {mf:.2f}~ms for motor sensing, with 95th percentiles of {p95:.2f} and {m95:.2f}~ms. Both measured processing times are below the 200-ms window interval. Reciprocal median processing rates are approximately {1000/pf:.2f} and {1000/mf:.2f} windows/s, respectively; these are workstation processing capacities, not measured embedded worst-case guarantees. Acquisition, scheduling, and any alarm-persistence logic must be included in a deployed timing budget.')+s[end:]
s=s.replace('Each variant used 10 warm-up executions and 50 timed repetitions.', 'Each variant used 10 warm-up executions and 50 timed repetitions, with variant order randomized within each repetition. Full, pruned, and ablated inputs used the same selective feature-extraction implementation.')
# Update timing mentions in the abstract, ablation discussion, and conclusion.
s=s.replace('from 22.37 to 12.32~ms',f"from {pf:.2f} to {ms('pcc','lf_time'):.2f}~ms")
s=s.replace('(1.82$\\times$)',f"({pf/ms('pcc','lf_time'):.2f}$\\times$)")
s=s.replace('16.28~ms (4.07$\\times$ faster than full)',f"{ms('motor','time_only'):.2f}~ms ({mf/ms('motor','time_only'):.2f}$\\times$ faster than full)")
(P/'main_revised.tex').write_text(s)

# Retain historical timing data alongside the current exports.
archive=R/'previous_family_level';archive.mkdir(exist_ok=True)
for name in ['runtime.csv','runtime_reductions.csv']:
    if not (archive/name).exists():shutil.copy2(D/name,archive/name)
runtime.to_csv(D/'runtime.csv',index=False)
reductions=runtime.query('stage=="end_to_end_processing"')[['stream','device','feature_set','median_ms','p95_ms']].copy()
for (stream,device),group in reductions.groupby(['stream','device']):
    base=group.loc[group.feature_set=='full','median_ms'].item()
    reductions.loc[group.index,'speedup']=base/group.median_ms
    reductions.loc[group.index,'latency_reduction_pct']=100*(1-group.median_ms/base)
reductions.to_csv(D/'runtime_reductions.csv',index=False)
# A compact, directly reviewable copy of all Table X values, including performance.
main=pd.read_csv(D/'main_mean_sd.csv');pruning=pd.read_csv(D/'pruning_summary.csv');rows=[]
for stream in ['pcc','motor']:
    for variant in variants.values():
        perf=main.query('task=="binary" and stream==@stream').iloc[0] if variant=='full' else pruning.query('stream==@stream and variant==@variant').iloc[0]
        row={'stream':stream,'variant':variant,**timing.loc[(stream,variant)].to_dict()}
        for metric in ['test_bal_acc','test_macro_f1']:
            for stat in ['mean','std']:row[metric+'_'+stat+'_pct']=100*perf[metric+'_'+stat]
        rows.append(row)
pd.DataFrame(rows).to_csv(R/'table_x.csv',index=False)
print('Updated Table X, full baseline Table IX, and dependent timing statements; BA/F1 retained.')
